# "name, arg = default, ..." as written in brms
signature <- function(name) {
  args <- formals(get(name, envir = asNamespace("brms")))
  no_default <- vapply(args, function(a) identical(a, quote(expr = )), TRUE)
  defaults <- vapply(args, function(a) paste(deparse(a), collapse = " "), "")
  paste0(names(args), ifelse(no_default, "", paste0(" = ", defaults)), collapse = ", ")
}

lines <- c(
  "# Generated by tools/generate.R; do not edit by hand.",
  "#",
  "# Functions with exactly the arguments of their brms counterparts: family constructors",
  "# (whose families brm() rejects) and functions metabeta does not support, which raise",
  "# an error explaining why.",
  ""
)
for (f in families) {
  family <- if (f == "Beta") "beta" else f
  lines <- c(lines,
    "#' @rdname brmsfamily", "#' @export",
    sprintf('%s <- function(%s) .brmsfamily("%s", link = link, slink = substitute(link))', f, signature(f), family), ""
  )
}
for (reason in names(unsupported)) {
  for (f in unsupported[[reason]]) {
    lines <- c(lines,
      "#' @rdname unsupported-brms", "#' @usage NULL", "#' @export",
      sprintf('%s <- function(%s) unsupported("%s", "%s")', f, signature(f), f, reason), ""
    )
  }
}
writeLines(lines, "R/generated.R")
